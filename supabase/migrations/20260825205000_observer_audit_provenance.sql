/* --- what this supersedes -------------------------------------------------- */

-- Two doors to the same counters is the drift this codebase avoids. The
-- implementation inside `observer` stays — `admit_ai_request` calls it — and
-- only the reachable façades go.
--
-- Sequencing matters and is stated rather than assumed: apply this migration
-- *before* deploying the code that calls the new names. Between the two, the
-- running build calls functions that no longer exist, the ceiling fails closed,
-- and Ask Observer refuses for as long as the deploy takes. Every measured
-- figure on every screen is unaffected, which is what makes that window
-- affordable.
drop function if exists public.consume_ai_quota(text, text, text, integer, integer, integer, integer);
drop function if exists public.record_ai_request(text, text, text, text, text, text, text, text[], integer, integer, integer, integer, integer);

/* --- the diagnostic leaves the browser ------------------------------------- */

-- `observer_whoami` earned its place: it proved the deployment was talking to a
-- different Supabase project by answering 200 to one caller and 404 to another.
-- That question is settled, and a release candidate should not ship a function
-- any holder of the browser key can call, however harmless its answer.
--
-- Revoked rather than dropped. It runs as the caller by design, which is the
-- whole point of it, and an operator holding the server key may still need to
-- ask which role they are. It is simply no longer reachable from a browser.
revoke execute on function public.observer_whoami() from anon, authenticated, public;
